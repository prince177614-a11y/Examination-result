// Quetion 1. -  Examination Result
// 90+ -> A+
// 80+ -> A
// 70+ -> B
// 60+ -> C
// 50+ -> D
// 40+ -> Fail



let marks = prompt("Enter your Examination marks");

if(marks > 100)
{
    console.log("MARKS JYADA NHI AAYEGA JITNA PADH LO")
}    
else if(marks > 90)
{
    console.log("A+")
}    
else if(marks > 80)
{
    console.log("A")
}    
else if(marks > 70)
{
    console.log("B")
}    
else if(marks > 60)
{
    console.log("C")
} 
else if(marks > 50)
{
    console.log("D")
} 
else if(marks > 40)
{
    console.log("Fail")
}          
